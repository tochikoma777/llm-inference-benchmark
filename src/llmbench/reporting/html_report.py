def report_filename(when: _dt.datetime | None = None) -> str:
    when = when or _dt.datetime.now()
    return f"benchmark_report_{when:%Y%m%d-%H%M}.html"


def _fmt(value: float | None, digits: int = 1, suffix: str = "") -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "—"
    return f"{value:.{digits}f}{suffix}"


def _table(frame: pd.DataFrame, columns: list[str] | None = None) -> str:
    if frame is None or frame.empty:
        return ""
    view = frame[columns] if columns else frame
    head = "".join(f"<th>{html.escape(str(c))}</th>" for c in view.columns)
    rows = []
    for _, row in view.iterrows():
        cells = []
        for value in row:
            if value is None or (isinstance(value, float) and pd.isna(value)):
                text = "—"
            elif isinstance(value, float) and float(value).is_integer():
                text = f"{value:,.0f}"
            elif isinstance(value, float):
                text = f"{value:,.2f}" if abs(value) < 1000 else f"{value:,.0f}"
            else:
                text = str(value)
            cells.append(f"<td>{html.escape(text)}</td>")
        rows.append(f"<tr>{''.join(cells)}</tr>")
    return (
        f'<div class="table-wrap"><table><thead><tr>{head}</tr></thead>'
        f'<tbody>{"".join(rows)}</tbody></table></div>'
    )


def _card(label_html: str, value: str, hint: str, accent: str = "blue") -> str:
    return (
        f'<div class="card kpi accent-{accent}">'
        f'<div class="kpi-label">{label_html}</div>'
        f'<div class="kpi-value">{html.escape(value)}</div>'
        f'<div class="kpi-hint">{html.escape(hint)}</div>'
        f"</div>"
    )


def _chart_block(
    builder: Callable[[Analysis], Any], analysis: Analysis, missing: str, span: int = 1
) -> str:
    try:
        figure = builder(analysis)
    except Exception:  # noqa: BLE001 - degrade instead of failing the report
        figure = None
    if figure is None:
        figure = charts.empty_figure(missing)
    div = figure.to_html(
        include_plotlyjs=False,
        full_html=False,
        config={"displayModeBar": False, "responsive": True},
        default_width="100%",
    )
    return f'<div class="card chart span-{span}">{div}</div>'


def _environment_table(analysis: Analysis) -> str:
    if not analysis.runs:
        return ""
    meta = analysis.runs[0].metadata
    system = meta.system or {}
    rows = [
        ("Run ID", meta.run_id),
        ("Backend", f"{meta.backend} ({meta.serving_mode})"),
        ("Model", meta.model_id or "—"),
        ("GPU", system.get("gpu_name") or "—"),
        ("Platform", system.get("platform") or "—"),
        ("Python", system.get("python") or "—"),
        ("Torch", (system.get("packages") or {}).get("torch") or "—"),
        ("vLLM", (system.get("packages") or {}).get("vllm") or "—"),
        ("Transformers", (system.get("packages") or {}).get("transformers") or "—"),
        ("Simulated", "yes" if analysis.is_mock else "no"),
    ]
    body = "".join(
        f"<tr><td class='muted'>{html.escape(str(k))}</td><td>{html.escape(str(v))}</td></tr>"
        for k, v in rows
    )
    return f'<div class="card"><table class="kv"><tbody>{body}</tbody></table></div>'


