def build_html_report(
    analysis: Analysis,
    out_path: Path | None = None,
    lang: str = "zh",
    embed_plotly: bool = True,
) -> Path:
    """Render the report and return the written path."""
    t = _I18N.get(lang, _I18N["zh"])
    out_path = Path(out_path) if out_path else reports_dir() / report_filename()
    out_path.parent.mkdir(parents=True, exist_ok=True)

    prime_series_colors(analysis.series())
    kpis = analysis.kpis()
    meta = analysis.runs[0].metadata if analysis.runs else None
    now = _dt.datetime.now().strftime("%Y-%m-%d %H:%M")

    # -- KPI cards --------------------------------------------------------
    cards: list[str] = []
    peak = kpis.get("peak_throughput_tok_s")
    if peak:
        cards.append(
            _card(
                t["kpi_peak_throughput"],
                f"{peak:,.0f} tok/s",
                f"{kpis.get('peak_throughput_backend','')} · "
                f"{t['at_concurrency']}={kpis.get('peak_concurrency','—')}",
                "blue",
            )
        )
    speedup = kpis.get("throughput_speedup")
    if speedup:
        cards.append(
            _card(
                t["kpi_speedup"],
                f"{speedup:.2f}×",
                f"{kpis.get('speedup_fastest','')} vs {kpis.get('speedup_baseline','')}",
                "emerald",
            )
        )
    if kpis.get("best_ttft_p95_ms") is not None:
        cards.append(
            _card(t["kpi_ttft"], format_ms(kpis["best_ttft_p95_ms"]), "under load", "violet")
        )
    if kpis.get("memory_saving_pct") is not None:
        cards.append(
            _card(
                t["kpi_memory"],
                f"{kpis['memory_saving_pct']:.0f}%",
                f"{kpis.get('memory_best_backend','')} @ "
                f"{format_tokens(kpis.get('kv_delta_at_tokens'))} tokens",
                "amber",
            )
        )
    if kpis.get("prefix_speedup"):
        cards.append(
            _card(
                t["kpi_prefix"],
                f"{kpis['prefix_speedup']:.2f}×",
                "multi-turn TTFT",
                "emerald",
            )
        )
    if kpis.get("best_policy"):
        cards.append(
            _card(
                t["kpi_policy"],
                str(kpis["best_policy"]).upper(),
                f"mean TTFT {format_ms(kpis.get('best_policy_ttft_ms'))}",
                "rose",
            )
        )
    kpi_html = "".join(cards) if cards else f'<div class="card">{t["no_data"]}</div>'

    comparison = analysis.comparison()
    comparison_html = (
        _table(comparison)
        if not comparison.empty
        else f'<p class="section-note">{t["no_data"]}</p>'
    )

    # -- charts -----------------------------------------------------------
    throughput_block = (
        '<div class="grid">'
        + _chart_block(charts.throughput_vs_concurrency, analysis, t["chart_missing"])
        + _chart_block(charts.throughput_speedup, analysis, t["chart_missing"])
        + "</div>"
    )
    latency_block = (
        '<div class="grid">'
        + _chart_block(charts.latency_vs_concurrency, analysis, t["chart_missing"])
        + _chart_block(charts.latency_cdf, analysis, t["chart_missing"])
        + "</div>"
    )
    efficiency_block = (
        '<div class="grid">'
        + _chart_block(charts.efficiency_pareto, analysis, t["chart_missing"])
        + _chart_block(charts.request_timeline, analysis, t["chart_missing"])
        + "</div>"
    )
    memory_block = (
        '<div class="grid">'
        + _chart_block(charts.memory_vs_sequence_length, analysis, t["chart_missing"])
        + _chart_block(charts.gpu_utilization, analysis, t["chart_missing"])
        + _chart_block(charts.ttft_vs_prompt_length, analysis, t["chart_missing"])
        + _chart_block(charts.tpot_vs_prompt_length, analysis, t["chart_missing"])
        + "</div>"
    )
    prefix_block = (
        '<div class="grid">'
        + _chart_block(charts.prefix_cache_rounds, analysis, t["chart_missing"], span=2)
        + "</div>"
    )
    scheduler_block = (
        '<div class="grid">'
        + _chart_block(charts.scheduler_policy_bars, analysis, t["chart_missing"])
        + _chart_block(charts.scheduler_group_split, analysis, t["chart_missing"])
        + "</div>"
    )

    scheduler_table = (
        _table(
            analysis.scheduler_frame()[
                [
                    c
                    for c in (
                        "extra_policy_label",
                        "ttft_ms_mean",
                        "ttft_ms_p95",
                        "ttft_ms_p99",
                        "e2e_ms_p99",
                        "throughput_tok_s",
                        "queue_ms_mean",
                        "extra_preemptions",
                        "extra_fairness_jain",
                    )
                    if c in analysis.scheduler_frame().columns
                ]
            ]
        )
        if analysis.has("scheduler")
        else ""
    )

    banner = f'<div class="banner">{t["mock_banner"]}</div>' if analysis.is_mock else ""

    chips = []
    if meta:
        chips.append(
            f'<span class="chip">{t["model"]}: <b>{html.escape(str(meta.model_id or "—"))}</b></span>'
        )
        gpu = (meta.system or {}).get("gpu_name")
        if gpu:
            chips.append(f'<span class="chip">{t["gpu"]}: <b>{html.escape(str(gpu))}</b></span>')
        chips.append(f'<span class="chip">{t["runs"]}: <b>{kpis["runs"]}</b></span>')
        chips.append(f'<span class="chip">{t["records"]}: <b>{kpis["records"]:,}</b></span>')
    chips.append(f'<span class="chip">{t["generated"]}: <b>{now}</b></span>')

    plotly_script = ""
    if embed_plotly:
        from plotly.offline import get_plotlyjs

        plotly_script = f"<script>{get_plotlyjs()}</script>"

    sections = [
        ("overview", t["overview"]),
        ("throughput", t["throughput"]),
        ("efficiency", t["efficiency"]),
        ("latency", t["latency"]),
        ("memory", t["memory"]),
        ("prefix", t["prefix"]),
        ("scheduler", t["scheduler"]),
        ("environment", t["environment"]),
    ]
    toc = "".join(f'<a href="#{anchor}">{name}</a>' for anchor, name in sections)

    html_doc = f"""<!DOCTYPE html>
<html lang="{'zh-CN' if lang == 'zh' else 'en'}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(t['title'])}</title>
<style>{_CSS}</style>
{plotly_script}
</head>
<body>
<div class="wrap">
  <header class="hero">
    <span class="eyebrow">LLMBench · v0.2</span>
    <h1>{html.escape(t['title'])}</h1>
    <p class="lede">{html.escape(t['subtitle'])}</p>
    <div class="chips">{''.join(chips)}</div>
    {banner}
  </header>

  <nav class="toc">{toc}</nav>

  <h2 id="overview">{t['overview']}</h2>
  <div class="grid-3">{kpi_html}</div>

  <h3 style="margin:28px 0 10px;font-size:16px;font-weight:600">{t['comparison']}</h3>
  <div class="card">{comparison_html}</div>

  <h2 id="throughput">{t['throughput']}</h2>
  {throughput_block}

  <h2 id="efficiency">{t['efficiency']}</h2>
  {efficiency_block}

  <h2 id="latency">{t['latency']}</h2>
  {latency_block}

  <h2 id="memory">{t['memory']}</h2>
  {memory_block}

  <h2 id="prefix">{t['prefix']}</h2>
  {prefix_block}

  <h2 id="scheduler">{t['scheduler']}</h2>
  {scheduler_block}
  {f'<div class="card" style="margin-top:18px">{scheduler_table}</div>' if scheduler_table else ''}

  <h2 id="environment">{t['environment']}</h2>
  {_environment_table(analysis)}

  <footer>{html.escape(t['footer'])}</footer>
</div>
</body>
</html>
"""
    out_path.write_text(html_doc, encoding="utf-8")

    # Sidecar JSON so the dashboard / other tools can reuse the KPIs.
    (out_path.parent / (out_path.stem + ".json")).write_text(
        json.dumps({"kpis": kpis, "generated_at": now}, indent=2, ensure_ascii=False, default=str),
        encoding="utf-8",
    )
    return out_path
